--   ON UPDATE 없음(updated_at은 코드에서 넣음), closed_date의 UNIQUE에 NULLS NOT DISTINCT(호텔 전체 휴무 중복도 막음)

CREATE TABLE member (
    member_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id    VARCHAR(50)  NOT NULL,
    password    VARCHAR(255) NOT NULL,
    name        VARCHAR(50)  NOT NULL,
    phone       VARCHAR(20),
    email       VARCHAR(100),
    role        VARCHAR(10)  NOT NULL DEFAULT 'USER',
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_member_login_id UNIQUE (login_id),
    CONSTRAINT uk_member_email UNIQUE (email),
    CONSTRAINT ck_member_role CHECK (role IN ('USER', 'ADMIN'))
);
CREATE UNIQUE INDEX uk_member_login_id_lower ON member (lower(login_id));  -- 1-A2 'Guest01' = 'guest01'
CREATE UNIQUE INDEX uk_member_email_lower ON member (lower(email));
COMMENT ON TABLE member IS '회원';
COMMENT ON COLUMN member.password IS '비밀번호 (scrypt$salt$hash)';
COMMENT ON COLUMN member.role IS 'USER(손님) / ADMIN(관리자)';

CREATE TABLE room_grade (                       -- 2-A1 객실 등급 (S · A · B · C)
    grade_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_code   CHAR(1)      NOT NULL,
    grade_name   VARCHAR(50)  NOT NULL,
    base_price   INT          NOT NULL,
    base_guest   INT          NOT NULL,
    max_guest    INT          NOT NULL,
    area_m2      INT          NOT NULL,
    bed_type     VARCHAR(30),
    intro        VARCHAR(300),
    sort_order   INT          NOT NULL DEFAULT 0,
    CONSTRAINT uk_room_grade_code UNIQUE (grade_code),
    CONSTRAINT uk_room_grade_name UNIQUE (grade_name),
    CONSTRAINT ck_room_grade_price CHECK (base_price > 0),
    CONSTRAINT ck_room_grade_guest CHECK (base_guest >= 1 AND max_guest >= base_guest)
);
COMMENT ON TABLE room_grade IS '객실 등급 (2-A1)';
COMMENT ON COLUMN room_grade.base_price IS '비수기 · 시티/마운틴뷰 기준 1박 요금 (리버뷰는 × 1.1)';
COMMENT ON COLUMN room_grade.bed_type IS '등급 기본 침대 (방마다 다르면 room.bed_type)';

CREATE TABLE room (
    room_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name    VARCHAR(100)  NOT NULL,
    room_type    VARCHAR(50)   NOT NULL,
    max_guest    INT           NOT NULL,
    price        INT           NOT NULL,
    description  VARCHAR(1000),
    view_count   INT           NOT NULL DEFAULT 0,
    is_active    CHAR(1)       NOT NULL DEFAULT 'Y',
    grade_id     BIGINT        REFERENCES room_grade (grade_id),
    view_type    VARCHAR(10),
    bed_type     VARCHAR(30),
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_room_name UNIQUE (room_name),
    CONSTRAINT ck_room_view_type CHECK (view_type IN ('RIVER', 'CITY', 'MOUNTAIN')),
    CONSTRAINT ck_room_max_guest CHECK (max_guest >= 1),
    CONSTRAINT ck_room_price     CHECK (price > 0),
    CONSTRAINT ck_room_is_active CHECK (is_active IN ('Y', 'N'))
);
COMMENT ON TABLE room IS '객실';
COMMENT ON COLUMN room.price IS '1박 요금';
COMMENT ON COLUMN room.view_count IS '조회수 (추천 점수에 사용)';
COMMENT ON COLUMN room.is_active IS '사용 여부 Y / N (N = 비활성화)';
COMMENT ON COLUMN room.grade_id IS '등급 (2-A1, NULL = 예전 객실)';
COMMENT ON COLUMN room.view_type IS '전망 RIVER / CITY / MOUNTAIN';

CREATE TABLE room_view (                        -- 1-A1 같은 사람 · 같은 방 · 같은 날은 1회
    room_id     BIGINT       NOT NULL REFERENCES room (room_id),
    viewer_key  VARCHAR(64)  NOT NULL,
    view_date   DATE         NOT NULL,
    CONSTRAINT pk_room_view PRIMARY KEY (room_id, viewer_key, view_date)
);
COMMENT ON TABLE room_view IS '객실 조회 기록 (1-A1)';
COMMENT ON COLUMN room_view.viewer_key IS '회원 M:<member_id> / 비회원 G:<쿠키 값>';
COMMENT ON COLUMN room_view.view_date IS '한국 날짜';

CREATE TABLE login_attempt (                    -- 1-A3 로그인 · 비밀번호 확인 실패 기록
    attempt_key  VARCHAR(80)  NOT NULL,
    failed_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_login_attempt ON login_attempt (attempt_key, failed_at);
COMMENT ON TABLE login_attempt IS '로그인 실패 기록 (1-A3, 최근 10분 5번이면 잠금)';
COMMENT ON COLUMN login_attempt.attempt_key IS 'login:<아이디> / password:<member_id> / reset:<아이디>';

CREATE TABLE closure (                          -- 3-A1 휴무 묶음 (한 번에 지정한 기간 하나)
    closure_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason_code  VARCHAR(20)  NOT NULL,
    reason       VARCHAR(200),
    created_by   BIGINT       REFERENCES member (member_id),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_closure_reason_code CHECK (reason_code IN ('CONSTRUCTION', 'MAINTENANCE', 'EVENT', 'CLOSURE', 'ETC'))
);
COMMENT ON TABLE closure IS '휴무 묶음 (3-A1). 기간은 남은 closed_date 행의 처음 · 끝으로 계산';
COMMENT ON COLUMN closure.reason_code IS '3-A2 공사 CONSTRUCTION / 점검 MAINTENANCE / 행사 EVENT / 휴관 CLOSURE / 기타 ETC';
COMMENT ON COLUMN closure.created_by IS '3-A3 지정한 관리자';

CREATE TABLE closed_date (
    closed_date_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT REFERENCES room (room_id),
    closed_date     DATE          NOT NULL,
    closure_id      BIGINT        NOT NULL REFERENCES closure (closure_id) ON DELETE CASCADE,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_closed_room_date UNIQUE NULLS NOT DISTINCT (room_id, closed_date)
);
CREATE INDEX idx_closed_date ON closed_date (closed_date);
COMMENT ON TABLE closed_date IS '예약 일자 (휴무일)';
CREATE INDEX idx_closed_closure ON closed_date (closure_id);
COMMENT ON COLUMN closed_date.room_id IS '객실 번호 (NULL = 호텔 전체 휴무)';
COMMENT ON COLUMN closed_date.closure_id IS '휴무 묶음 (3-A1). 사유 · 지정자는 묶음에 한 번만';

CREATE TABLE reservation (
    reservation_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       BIGINT       NOT NULL REFERENCES member (member_id),
    room_id         BIGINT       NOT NULL REFERENCES room (room_id),
    check_in_date   DATE         NOT NULL,
    check_out_date  DATE         NOT NULL,
    guest_count     INT          NOT NULL,
    total_price     INT          NOT NULL,
    status          VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    request_memo    VARCHAR(200),
    price_per_night INT          NOT NULL,
    canceled_at     TIMESTAMP,
    canceled_by     BIGINT       REFERENCES member (member_id),
    cancel_reason   VARCHAR(200),
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reservation_night_price CHECK (price_per_night > 0),
    CONSTRAINT ck_reservation_canceled CHECK ((status = 'CANCELED') = (canceled_at IS NOT NULL)),  -- 4-A4
    -- 4-A1 이중 예약을 DB가 막는다: 살아 있는 예약끼리 같은 방에서 날짜가 겹치면 저장 불가(위반 = SQLSTATE 23P01 → 409)
    -- '[)' = 체크인 포함 · 체크아웃 제외(체크아웃 날 다음 손님 체크인 가능). 이 제약의 GiST 인덱스가 겹침 검색에도 쓰인다
    CONSTRAINT ex_reservation_no_overlap EXCLUDE USING gist (
        room_id WITH =,
        daterange(check_in_date, check_out_date, '[)') WITH &&
    ) WHERE (status IN ('PENDING', 'APPROVED')),
    CONSTRAINT ck_reservation_dates  CHECK (check_out_date > check_in_date),
    CONSTRAINT ck_reservation_guest  CHECK (guest_count >= 1),
    CONSTRAINT ck_reservation_price  CHECK (total_price >= 0),
    CONSTRAINT ck_reservation_status CHECK (status IN ('PENDING', 'APPROVED', 'CANCELED'))
);
CREATE INDEX idx_reservation_member ON reservation (member_id);
CREATE INDEX idx_reservation_live ON reservation (room_id, check_in_date)
    WHERE status IN ('PENDING', 'APPROVED');   -- 4-A2 살아 있는 예약만 (옛 room_dates · status 인덱스는 ③에서 삭제)
COMMENT ON TABLE reservation IS '객실 예약';
COMMENT ON COLUMN reservation.status IS 'PENDING(대기) / APPROVED(승인) / CANCELED(취소)';
COMMENT ON COLUMN reservation.updated_at IS '상태 바뀐 시각 (코드에서 갱신)';
COMMENT ON COLUMN reservation.price_per_night IS '4-A3 예약 때의 1박 요금';
COMMENT ON COLUMN reservation.canceled_at IS '4-A4 취소 시각 (CANCELED 일 때만 값이 있음, ck_reservation_canceled)';
COMMENT ON COLUMN reservation.canceled_by IS '4-A4 취소한 회원 (손님 본인 또는 관리자)';

CREATE TABLE attach_file (
    file_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type    VARCHAR(30)   NOT NULL,
    target_id      BIGINT        NOT NULL,
    original_name  VARCHAR(255)  NOT NULL,
    saved_path     VARCHAR(500)  NOT NULL,
    file_size      BIGINT        NOT NULL,
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_attach_target ON attach_file (target_type, target_id);
COMMENT ON TABLE attach_file IS '첨부파일 (공통)';
COMMENT ON COLUMN attach_file.target_type IS '어디 파일인지 (예: ROOM)';

CREATE TABLE menu (
    menu_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT REFERENCES menu (menu_id),
    menu_name   VARCHAR(50)   NOT NULL,
    menu_url    VARCHAR(200),
    role        VARCHAR(10)   NOT NULL DEFAULT 'USER',
    sort_order  INT           NOT NULL DEFAULT 0,
    is_used     CHAR(1)       NOT NULL DEFAULT 'Y',
    CONSTRAINT ck_menu_role    CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_menu_is_used CHECK (is_used IN ('Y', 'N'))
);
CREATE INDEX idx_menu_parent ON menu (parent_id);
COMMENT ON TABLE menu IS '메뉴 (공통)';

